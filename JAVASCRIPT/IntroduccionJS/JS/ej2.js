
//Pido cadena de texto
var cadena = prompt("Introduce una cadena de texto:");

//Pido un número
var numero = prompt("Introduce un número:");

//En la posición Y de la cadena "XXXX" se encuentra el carácter "X"
var caracter = cadena[numero];   
document.write("<h1>En la posición " + numero + " se encuentra el carácter: " + caracter + "</h1>");